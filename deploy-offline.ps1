# =====================================================================
# deploy-offline.ps1  -  Campus Information Platform Offline Installer
#
# ONE-CLICK deployment on a machine that has Docker Desktop installed
# but NO images loaded and NO containers created yet.
#
# It is IDEMPOTENT: safe to re-run after a partial failure.
#
# What it does, in order:
#   1. Check Docker engine is up
#   2. docker load every offline image tar（docker load 本身幂等，
#      已存在的镜像重复 load 不会出错，所以这里不做"跳过"判断）
#   3. docker compose up -d  (project name: school-platform)
#   4. Wait until supabase-db is healthy
#   5. Apply db-prepare.sql  (auth schema / pgcrypto / postgres role)
#      -> 坑：不做这一步 gotrue 首次启动就会崩："schema auth does not exist"
#         （迁移里还硬编码 GRANT ... TO postgres，而容器超管叫 supabase，
#          所以 postgres 角色也必须在这里先建出来）
#   6. Restart supabase-auth and wait until its migrations are applied
#   7. Apply business init SQL  docker\init\NN_*.sql  (01..15, in name order)
#      -> 坑：文件之间是有依赖的（早期 05 引用了 06 才加的 schools.name 列），
#         所以必须按文件名排序整目录执行，不能按字母序乱跑
#      - 02_features_v2.sql is the FIXED copy (CREATE POLICY IF NOT EXISTS
#        is not valid Postgres -> DROP + CREATE, generated by deployer)
#      - 08_fix_seed_auth.sql backfills auth.identities, zeroes instance_id
#        and un-nulls token columns for the 4 seed accounts
#      - 09_school_isolation_rls.sql  多校数据隔离（按 school_id 的 RLS）
#      - 10_class_inspection.sql      班级检查扣分记录表
#      - 11_inspection_categories.sql 检查项目字典表（可自定义项目）
#      - 12_inspection_base_score.sql 项目满分（基础分）+ 默认 8 项初始化
#      - 13_purge_user_account.sql    删除档案时同步清理登录凭据（触发器）
#      - 14_borrow_schema_merge.sql   借阅表结构合并（存量库补列 / 改名 / 清重复索引）
#      - 15_profile_metadata_sync.sql 档案变更后同步登录元数据（JWT 里的 class_id）
#   8. Restart supabase-rest so PostgREST refreshes its schema cache
#   9. Smoke-test: front page, login of admin@demo.com, data query
#
# Run from the project folder (where docker-compose.yml lives):
#     powershell -ExecutionPolicy Bypass -File .\deploy-offline.ps1
# =====================================================================

$ErrorActionPreference = 'Stop'
$Project = $PSScriptRoot
Set-Location $Project

# ---------- 控制台输出小工具（统一三种前缀的配色） ----------

<#
.SYNOPSIS  打印一个步骤标题。
.PARAMETER Message 步骤描述
#>
function Write-Step([string]$Message) { Write-Host "`n=== $Message ===" -ForegroundColor Cyan }

<#
.SYNOPSIS  打印成功提示。
.PARAMETER Message 提示内容
#>
function Write-OK([string]$Message)   { Write-Host "  [OK] $Message" -ForegroundColor Green }

<#
.SYNOPSIS  打印失败提示并立即终止脚本。
.PARAMETER Message 失败原因
.NOTES  以 exit 1 结束整个部署流程，不会继续往下跑。
#>
function Write-Fail([string]$Message) { Write-Host "  [X] $Message" -ForegroundColor Red; exit 1 }

# ---------- helpers to run a local SQL file inside the db container ----------

<#
.SYNOPSIS  把一个本地 SQL 文件拷进 supabase-db 容器并用 psql 执行。
.PARAMETER SqlFilePath 本地 SQL 文件绝对路径
.PARAMETER StepLabel  该步骤在控制台上的中文说明
.NOTES
  -v ON_ERROR_STOP=1：让 psql 遇到第一条报错就返回非 0，
  否则脚本会"看起来执行成功"但后面一半语句其实全没跑。
#>
function Invoke-DbSql([string]$SqlFilePath, [string]$StepLabel) {
    $SqlFileName = Split-Path $SqlFilePath -Leaf
    Write-Step "Apply $StepLabel ($SqlFileName)"
    docker cp $SqlFilePath "supabase-db:/tmp/$SqlFileName" | Out-Null
    if ($LASTEXITCODE -ne 0) { Write-Fail "docker cp failed for $SqlFileName" }
    docker exec supabase-db psql -U supabase -d postgres -v ON_ERROR_STOP=1 -f "/tmp/$SqlFileName" 2>&1 | Out-Host
    if ($LASTEXITCODE -ne 0) { Write-Fail "psql failed on $SqlFileName" }
    Write-OK "$SqlFileName applied"
}

<#
.SYNOPSIS  轮询等待 supabase-db 容器健康检查通过。
.PARAMETER MaxSeconds 最长等待秒数，默认 120；每 5 秒探测一次
.NOTES  超时后直接 Write-Fail 退出，不继续做后续依赖数据库的步骤。
#>
function Wait-DbHealthy([int]$MaxSeconds = 120) {
    Write-Step "Wait for supabase-db healthy"
    $Attempt = 0
    while ($Attempt -lt ($MaxSeconds / 5)) {
        $DbHealth = docker inspect --format '{{.State.Health.Status}}' supabase-db 2>$null
        if ($DbHealth -eq 'healthy') { Write-OK 'database healthy'; return }
        Start-Sleep -Seconds 5; $Attempt++
    }
    Write-Fail 'database not healthy in time'
}

<#
.SYNOPSIS  重启 supabase-auth 并轮询等待 GoTrue 完成迁移、API 就绪。
.PARAMETER MaxSeconds 最长等待秒数，默认 180；每 5 秒探测一次
.NOTES
  坑：迁移失败时容器会一直重启，光等超时看不出原因，
  所以额外匹配 "schema ... does not exist" 提前报出"没跑 db-prepare.sql"。
#>
function Wait-AuthReady([int]$MaxSeconds = 180) {
    Write-Step "Restart auth & wait for GoTrue migrations"
    docker restart supabase-auth | Out-Null
    $Attempt = 0
    while ($Attempt -lt ($MaxSeconds / 5)) {
        Start-Sleep -Seconds 5
        $AuthLogs = docker logs supabase-auth 2>&1 | Out-String
        if ($AuthLogs -match 'GoTrue API started') { Write-OK 'GoTrue API ready'; return }
        # detect fatal crash early
        if ($AuthLogs -match 'schema .* does not exist') {
            Write-Fail 'auth schema missing - run db-prepare.sql first (step 5)'
        }
        $Attempt++
    }
    Write-Fail 'GoTrue did not become ready in time (check: docker logs supabase-auth)'
}

# =====================================================================
Write-Step "0. Pre-flight: Docker engine"
docker info *> $null
if ($LASTEXITCODE -ne 0) { Write-Fail 'Docker is not running. Start Docker Desktop first.' }
Write-OK "docker engine reachable (docker $(docker version --format '{{.Server.Version}}' 2>$null))"

# ---------- 1. load offline images ----------
Write-Step "1. Load offline images"
# 离线镜像 tar 放在包外一层的 docker-images 目录下（与 project 同级）
$ImagesDir = Join-Path (Split-Path $Project -Parent) 'docker-images'
if (-not (Test-Path $ImagesDir)) { Write-Fail "docker-images folder not found: $ImagesDir" }
# 坑：tar 里的镜像必须已经是标准名（postgres:15-alpine 这种），
#     带加速源前缀（docker.m.daocloud.io/...）在离线机上 compose 会找不到镜像
Get-ChildItem "$ImagesDir\*.tar" | ForEach-Object {
    Write-Host "  loading $($_.Name) ..." -ForegroundColor DarkGray
    docker load -i $_.FullName 2>&1
}
Write-OK 'offline images loaded'

# ---------- 2. compose up ----------
Write-Step "2. docker compose up -d"
docker compose -p school-platform up -d 2>&1 | Out-Host
if ($LASTEXITCODE -ne 0) { Write-Fail 'docker compose up failed' }
Write-OK 'containers started'

Wait-DbHealthy

# ---------- 3. db prerequisites ----------
Invoke-DbSql (Join-Path $Project 'db-prepare.sql') 'db prerequisites (auth schema / pgcrypto / postgres role)'

# ---------- 4. restart auth, wait for its 50 migrations ----------
Wait-AuthReady

# ---------- 5. business init SQL 01..15 ----------
Write-Step "5. Apply business init SQL (docker\init\NN_*.sql)"
$InitSqlDir = Join-Path $Project 'docker\init'
# 只挑 NN_ 前缀的业务脚本，并按名字排序执行——顺序错了会因为跨文件依赖而失败
Get-ChildItem "$InitSqlDir\*.sql" | Where-Object { $_.Name -match '^\d{2}_' } | Sort-Object Name | ForEach-Object {
    Invoke-DbSql $_.FullName "business init"
}

# ---------- 6. refresh PostgREST schema cache ----------
Write-Step "6. Restart supabase-rest (refresh schema cache)"
docker restart supabase-rest | Out-Null
Write-OK 'rest restarted'

# ---------- 7. smoke test ----------
